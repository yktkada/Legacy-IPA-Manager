    private static CultureInfo? s_culture;
    private static readonly AsyncLocal<CultureInfo?> s_asyncCulture = new();

    public static CultureInfo? Culture
    {
        get => s_asyncCulture.Value ?? s_culture;
        set => s_culture = value;
    }

    internal static IDisposable UseCultureScope(CultureInfo? culture)
    {
        var previous = s_asyncCulture.Value;
        s_asyncCulture.Value = culture;
        return new CultureScope(previous);
    }

    private sealed class CultureScope(CultureInfo? previous) : IDisposable
    {
        public void Dispose() => s_asyncCulture.Value = previous;
    }

    internal static ResourceManager ResourceManager => s_resourceManager;

    internal static string Get(string key)
        => s_resourceManager.GetString(key, Culture ?? CultureInfo.CurrentUICulture) ?? key;

    internal static string Format(string key, params object?[] args)
        => string.Format(Culture ?? CultureInfo.CurrentUICulture, Get(key), args);

