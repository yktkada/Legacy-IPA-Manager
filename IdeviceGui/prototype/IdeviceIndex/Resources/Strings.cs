    public static CultureInfo? Culture
    {
        get => s_asyncCulture.Value ?? s_culture;
        set => s_culture = value;
    }

    internal static IDisposable UseCultureScope(CultureInfo? culture)
    {
        var previous = s_asyncCulture.Value;
        s_asyncCulture.Value = culture;
        return new CultureScope(previous);
    }

    private sealed class CultureScope(CultureInfo? previous) : IDisposable
    {
        public void Dispose() => s_asyncCulture.Value = previous;
    }

